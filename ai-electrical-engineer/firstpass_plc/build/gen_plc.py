"""Write the PLC deliverables from a built Program.

  <job>_Program.L5X      Studio 5000 program import (Rockwell L5X, program level)
  <job>_HMI_Tags.csv     tags the PanelView reads and writes
  <job>_IO_Map.csv       every I/O point: address, module channel, PLC tag
  <job>_Ladder.md        every rung with its comment, for review without Studio 5000

The L5X is a *program* import: it carries the program, its tags and its
routines. The controller and the 5069 I/O modules are created once in
Studio 5000 (see the report); the mapping routines then connect to them.
"""
from datetime import datetime
from xml.sax.saxutils import quoteattr
import csv
import xml.etree.ElementTree as ET

SOFTWARE_REVISION = "30.00"  # oldest Studio 5000 the export claims; 5069-L306ER needs v30+
READ_WRITE_ROLES = {"HMI", "PARAM"}


def _cdata(text):
    return "<![CDATA[" + text.replace("]]>", "]]]]><![CDATA[>") + "]]>"


def _l5k_real(v):
    mant, exp = f"{float(v):.8e}".split("e")
    return f"{mant}e{int(exp):+04d}"


def _tag_xml(t):
    access = "Read/Write" if t.role in READ_WRITE_ROLES else "Read Only"
    radix = {"BOOL": ' Radix="Decimal"', "DINT": ' Radix="Decimal"', "REAL": ' Radix="Float"'}.get(t.datatype, "")
    out = [f'<Tag Name={quoteattr(t.name)} TagType="Base" DataType="{t.datatype}"{radix} '
           f'Constant="false" ExternalAccess="{access}">']
    if t.description:
        out.append(f"<Description>{_cdata(t.description)}</Description>")
    if t.datatype == "TIMER":
        out.append(f'<Data Format="L5K">{_cdata(f"[0,{t.preset},0]")}</Data>')
        out.append('<Data Format="Decorated"><Structure DataType="TIMER">'
                   f'<DataValueMember Name="PRE" DataType="DINT" Radix="Decimal" Value="{t.preset}"/>'
                   '<DataValueMember Name="ACC" DataType="DINT" Radix="Decimal" Value="0"/>'
                   '<DataValueMember Name="EN" DataType="BOOL" Value="0"/>'
                   '<DataValueMember Name="TT" DataType="BOOL" Value="0"/>'
                   '<DataValueMember Name="DN" DataType="BOOL" Value="0"/>'
                   "</Structure></Data>")
    elif t.datatype == "REAL":
        out.append(f'<Data Format="L5K">{_cdata(_l5k_real(t.value))}</Data>')
        out.append(f'<Data Format="Decorated"><DataValue DataType="REAL" Radix="Float" Value="{float(t.value)!r}"/></Data>')
    else:
        v = int(t.value)
        out.append(f'<Data Format="L5K">{_cdata(str(v))}</Data>')
        out.append(f'<Data Format="Decorated"><DataValue DataType="{t.datatype}" Radix="Decimal" Value="{v}"/></Data>')
    out.append("</Tag>")
    return "\n".join(out)


def l5x_text(program, job):
    date = datetime.strptime(job.project["date"], "%m-%d-%Y").strftime("%a %b %d %H:%M:%S %Y")
    lines = [
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>',
        f'<RSLogix5000Content SchemaRevision="1.0" SoftwareRevision="{SOFTWARE_REVISION}" '
        f'TargetName={quoteattr(program.name)} TargetType="Program" TargetClass="Standard" '
        f'ContainsContext="true" ExportDate="{date}" '
        'ExportOptions="References NoRawData L5KData DecoratedData Context Dependencies '
        'ForceProtectedEncoding AllProjDocTrans">',
        f'<Controller Use="Context" Name={quoteattr(program.controller)}>',
        '<DataTypes Use="Context">', "</DataTypes>",
        '<Tags Use="Context">', "</Tags>",
        '<Programs Use="Context">',
        f'<Program Use="Target" Name={quoteattr(program.name)} TestEdits="false" '
        f'MainRoutineName={quoteattr(program.main)} Disabled="false" Class="Standard" UseAsFolder="false">',
        f"<Description>{_cdata(_program_description(job))}</Description>",
        "<Tags>",
    ]
    lines += [_tag_xml(t) for t in sorted(program.tags.values(), key=_tag_order)]
    lines.append("</Tags>")
    lines.append("<Routines>")
    for r in program.routines:
        lines.append(f'<Routine Name={quoteattr(r.name)} Type="RLL">')
        lines.append(f"<Description>{_cdata(r.description)}</Description>")
        lines.append("<RLLContent>")
        for n, g in enumerate(r.rungs):
            lines.append(f'<Rung Number="{n}" Type="N">')
            if g.comment:
                lines.append(f"<Comment>{_cdata(g.comment)}</Comment>")
            lines.append(f"<Text>{_cdata(g.text)}</Text>")
            lines.append("</Rung>")
        lines += ["</RLLContent>", "</Routine>"]
    lines += ["</Routines>", "</Program>", "</Programs>", "</Controller>", "</RSLogix5000Content>", ""]
    return "\n".join(lines)


def _program_description(job):
    p = job.project
    return (f"{p['project']} {p['title']} for {p['customer']}. Drawing {p['drawing']} Rev {p['revision']}. "
            f"Generated by FirstPass gen_plc.py from data/ - do not edit by hand; change the data or the "
            f"rules and rebuild.")


ROLE_ORDER = ["DI", "AI", "DO", "AO", "HMI", "PARAM", "STATUS", "ALARM", "TIMER", "INTERNAL"]


def _tag_order(t):
    return ROLE_ORDER.index(t.role), t.io.address if t.io else "", t.name


def check_l5x(text, program):
    """Parse the L5X back and confirm every routine and rung survived."""
    root = ET.fromstring(text.encode("utf-8"))
    prog = root.find("./Controller/Programs/Program")
    got = {r.get("Name"): [x.text for x in r.findall("./RLLContent/Rung/Text")] for r in prog.findall("./Routines/Routine")}
    want = {r.name: [g.text for g in r.rungs] for r in program.routines}
    tags = {t.get("Name") for t in prog.findall("./Tags/Tag")}
    return got == want and tags == set(program.tags)


def write_all(program, job, out_dir):
    out_dir.mkdir(parents=True, exist_ok=True)
    stem = job.project["project"]
    files = {}

    text = l5x_text(program, job)
    if not check_l5x(text, program):
        raise RuntimeError("L5X did not round-trip: routines, rungs or tags differ after parsing")
    files["l5x"] = out_dir / f"{stem}_Program.L5X"
    files["l5x"].write_text(text, encoding="utf-8")

    files["hmi"] = out_dir / f"{stem}_HMI_Tags.csv"
    with open(files["hmi"], "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["tag", "type", "hmi_access", "reference", "description"])
        for t in sorted(program.tags.values(), key=_tag_order):
            if t.role in ("HMI", "STATUS", "ALARM"):
                access = "write" if t.role == "HMI" else "read"
                w.writerow([t.name, t.datatype, access, f"{{[PLC]Program:{program.name}.{t.name}}}", t.description])

    files["io"] = out_dir / f"{stem}_IO_Map.csv"
    with open(files["io"], "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["address", "module", "slot", "module_channel", "plc_tag", "device_tag", "description",
                    "wire", "terminal", "panel", "sheet", "status"])
        for p in job.io:
            status = "spare" if p.spare else "live"
            if not p.path:
                status = "does not exist on module"
            w.writerow([p.address, p.module, p.slot, p.path, p.tag if not p.spare else "", p.device_tag,
                        p.description, p.wire, p.terminal, p.panel, p.sheet, status])

    files["ladder"] = out_dir / f"{stem}_Ladder.md"
    files["ladder"].write_text(ladder_listing(program, job), encoding="utf-8")
    return files


def ladder_listing(program, job):
    p = job.project
    out = [f"# {p['project']} {p['title']} - ladder listing", "",
           f"Program `{program.name}`, {len(program.routines)} routines, "
           f"{sum(len(r.rungs) for r in program.routines)} rungs, {len(program.tags)} tags. "
           "Generated from data/ by build/gen_plc.py; this is the same rung text that is in the L5X.", ""]
    for r in program.routines:
        out += [f"## {r.name}", "", r.description, ""]
        for n, g in enumerate(r.rungs):
            out.append(f"**{n}.** {g.comment}" if g.comment else f"**{n}.**")
            out += ["", "```", g.text, "```", ""]
    return "\n".join(out)
